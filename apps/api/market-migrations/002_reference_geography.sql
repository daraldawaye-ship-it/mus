-- Fixed administrative geographic reference lists. These are NOT public cards
-- and have no create/edit UI. Owners maintain them through reviewed migrations.
CREATE TABLE IF NOT EXISTS market_reference_entries (
  kind text NOT NULL CHECK(kind IN ('country','governorate','city')),
  code text NOT NULL CHECK(code ~ '^[A-Za-z0-9_-]{2,48}$'),
  name text NOT NULL CHECK(length(trim(name)) BETWEEN 1 AND 150),
  parent_code text,
  PRIMARY KEY(kind,code),
  UNIQUE(kind,name),
  CHECK ((kind='country' AND parent_code IS NULL) OR
         (kind IN ('governorate','city') AND parent_code IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS market_reference_parent
  ON market_reference_entries(kind,parent_code,name);
